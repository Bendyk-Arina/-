import math

def calculate_Y(x, a, b, c):
    # Перевірка області допустимих значень (ОДЗ) для логарифма
    # Аргумент логарифма |a| має бути строго більшим за 0, тому a не може дорівнювати 0
    if a == 0:
        return "Помилка: 'a' не може дорівнювати 0, оскільки логарифм від 0 не існує."
    
    try:
        # Обчислюємо x у квадраті
        part1 = x**2
        
        # Обчислюємо натуральний логарифм від модуля a
        part2 = math.log(abs(a))
        
        # Обчислюємо синус b, помножений на квадратний корінь із модуля c
        part3 = math.sin(b) * math.sqrt(abs(c))
        
        # Підсумкове значення виразу Y
        Y = part1 + part2 - part3
        return Y
        
    except Exception as e:
        # Відловлюємо будь-які інші непередбачені помилки
        return f"Сталася непередбачена помилка при обчисленні: {e}"

# Блок введення даних та виведення результату
try:
    print("Введіть значення для змінних:")
    x_val = float(input("x = "))
    a_val = float(input("a = "))
    b_val = float(input("b = (у радіанах) "))
    c_val = float(input("c = "))
    
    # Виклик функції та друк результату
    result = calculate_Y(x_val, a_val, b_val, c_val)
    print(f"\nРезультат обчислення виразу: Y = {result}")
    
except ValueError:
    print("Помилка введення: Будь ласка, вводьте лише числа (для десяткових дробів використовуйте крапку).")