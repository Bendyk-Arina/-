
number = int(input("Введіть число від 1 до 4: "))

# Визначення пори року за допомогою розгалуження
if number == 1:
    print("Зима")
elif number == 2:
    print("Весна")
elif number == 3:
    print("Літо")
elif number == 4:
    print("Осінь")
else:
    print("Помилка: введено некоректне число!")