фірми = {}
кількість = int(input("Введіть кількість фірм для введення: "))

for i in range(кількість):
    назва = input(f"Введіть назву фірми №{i+1}: ")
    активи = float(input(f"Введіть оборотні активи фірми {назва}: "))
    фірми[назва] = активи

# Обчислення сумарних активів
сума_активів = sum(фірми.values())

# Знаходження фірми з найбільшими та найменшими активами
фірма_max = max(фірми, key=фірми.get)
фірма_min = min(фірми, key=фірми.get)

print("\nРезультати обчислень:")
print(f"Сумарні активи всіх фірм: {сума_активів}")
print(f"Фірма з найбільшими активами: {фірма_max} ({фірми[фірма_max]})")
print(f"Фірма з найменшими активами: {фірма_min} ({фірми[фірма_min]})")   