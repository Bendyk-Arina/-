# Створення початкової множини А з числами від 1 до 25
А = set(range(1, 26))

# Створення двох порожніх множин
В = set()  # сюди підуть числа, що діляться на 3
С = set()  # сюди підуть усі інші числа

for x in А:
    # Перевіряємо, чи ділиться число на 3 без остачі
    if x % 3 == 0:
        В.add(x)
    else:
        С.add(x)

print("B:",  В)
print("C:",  С)